const { test, expect } = require('../saved-views-actual-fixture.cjs');
const { enterSecondaryDocument } = require('../secondary-document-entry');

for (const sort of ['recent_reverse', 'alphabetical_reverse', 'deadline_reverse', 'status_reverse']) test(`saved Matter views retain ${sort} and the last-updated filter through both workspaces`, async ({ page, baseURL }, info) => {
  const observed = { errors: [] };
  page.on('pageerror', error => observed.errors.push(error.message));
  const panel = page.locator('[data-saved-views]');
  const owner = (await (await page.request.get('/api/auth/me')).json()).user;
    const target = `/attorney-v2.html#/matters?matterSort=${sort}&matterUpdated=30_days`;
    if (page.url() === 'about:blank') await enterSecondaryDocument(page, new URL(target, baseURL).href);
    else await page.goto(target, { waitUntil: 'domcontentloaded' });
    await expect(panel).toHaveAttribute('data-state', 'ready');
    await page.getByRole('button', { name: 'Save applied view', exact: true }).click();
    await panel.getByRole('textbox', { name: 'View name', exact: true }).fill(`Current ${sort}`);
    await panel.getByRole('button', { name: 'Save view', exact: true }).click();
    await expect(page.locator('.av2-saved-views-host > [role=status]')).toHaveText('View saved.');
    const response = await page.request.get(`/api/account/dashboard-views?scope=attorney_matters&expectedOwnerId=${owner.id || owner._id}`);
    expect(response.status()).toBe(200);
    const stored = (await response.json()).views.find(view => view.name === `Current ${sort}`);
    expect(stored.filters.sort).toBe(sort);
    expect(stored.filters.updated).toBe('30_days');
    await page.locator('#av2-saved-views').selectOption('builtin:active');
    await expect(page).toHaveURL(/view=active/);
    await expect(panel).toHaveAttribute('data-state', 'ready');
    await page.locator('#av2-saved-views').selectOption(`saved:${stored.id}`);
    await expect(page).toHaveURL(new RegExp(`matterSort=${sort}`));
    await expect(page).toHaveURL(/matterUpdated=30_days/);
    await expect(page.getByRole('combobox', { name: 'Sort Matters', exact: true })).toHaveValue(sort);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await expect(panel).toHaveAttribute('data-state', 'ready');
    await expect(page.getByRole('combobox', { name: 'Sort Matters', exact: true })).toHaveValue(sort);
    await expect(page.locator('#av2-matterUpdated')).toHaveValue('30_days');
    await page.goto('/dashboard-attorney.html#cases:active', { waitUntil: 'domcontentloaded' });
    await expect(panel).toHaveAttribute('data-state', 'ready');
    await page.locator('[data-matter-saved-view]').selectOption(`saved:${stored.id}`);
    await expect(page.locator('[data-matter-sort]')).toHaveValue(sort);
    await expect(page.locator('[data-matter-updated-filter]')).toHaveValue('30_days');
    await expect(page).toHaveURL(new RegExp(`matterSort=${sort}`));
    await page.reload({ waitUntil: 'domcontentloaded' });
    await expect(panel).toHaveAttribute('data-state', 'ready');
    await expect(page.locator('[data-matter-sort]')).toHaveValue(sort);
    await expect(page.locator('[data-matter-updated-filter]')).toHaveValue('30_days');
    await page.screenshot({ path: info.outputPath(`retained-${sort}.png`) });
  expect(observed.errors).toEqual([]);
});
